export function normalizeLanguageCode(languageCode) {
	return normalizeSupportedLanguageCode(languageCode) || DEFAULT_LANG;
}

function normalizeSupportedLanguageCode(languageCode) {
	if (!languageCode) {
		return undefined;
	}
	const code = String(languageCode).trim().toLowerCase().replace('_', '-');
	if (!code || code === 'auto') {
		return undefined;
	}
	const [baseCode] = code.split('-');
	return SUPPORTED_LANGS.includes(baseCode) ? baseCode : undefined;
}

function getMessageLocaleText(msg) {
	const values = [
		msg?.from?.first_name,
		msg?.from?.last_name,
		msg?.from?.username,
		msg?.chat?.first_name,
		msg?.chat?.last_name,
		msg?.chat?.title,
		msg?.chat?.username,
		msg?.reply_to_message?.from?.first_name,
		msg?.reply_to_message?.from?.last_name,
		msg?.reply_to_message?.from?.username,
		msg?.reply_to_message?.chat?.first_name,
		msg?.reply_to_message?.chat?.last_name,
		msg?.reply_to_message?.chat?.title,
		msg?.reply_to_message?.chat?.username,
		msg?.forward_from?.first_name,
		msg?.forward_from?.last_name,
		msg?.forward_from?.username,
		msg?.forward_from_chat?.title,
		msg?.forward_from_chat?.username,
	];

	return values.filter(Boolean).join(' ');
}

export function detectLocaleFromText(text) {
	if (!text) {
		return undefined;
	}

	const value = String(text);
	const scriptLocale = SCRIPT_LOCALE_RULES.find(({ regex }) => regex.test(value));
	if (scriptLocale) {
		return scriptLocale.lang;
	}

	const latinLocale = LATIN_LOCALE_RULES.find(({ regex }) => regex.test(value));
	return latinLocale?.lang;
}

export function getLocale(env, msg) {
	const configuredLang = env?.BOT_LANGUAGE;
	if (configuredLang && String(configuredLang).trim().toLowerCase() !== 'auto') {
		return normalizeLanguageCode(configuredLang);
	}

	return detectLocaleFromText(getMessageLocaleText(msg)) || normalizeSupportedLanguageCode(msg?.from?.language_code) || DEFAULT_LANG;
}

export function t(lang, key) {
	return localeText[lang]?.[key] || localeText[DEFAULT_LANG][key] || key;
}
